export interface ImageMetadata {
  fileName: string;
  fileSizeKB: number;
  mimeType: string;
  width: number;
  height: number;
}

export interface ImageDescriptionResult {
  mode: 'api' | 'demo';
  description: string;
  details: string;
}

const VISION_API_URL = import.meta.env.VITE_VISION_API_URL as string | undefined;
const VISION_API_KEY = import.meta.env.VITE_VISION_API_KEY as string | undefined;

export function isVisionApiConfigured(): boolean {
  return Boolean(VISION_API_URL && VISION_API_URL.trim().length > 0);
}

export function readImageMetadata(file: File, previewUrl: string): Promise<ImageMetadata> {
  return new Promise((resolve) => {
    const img = new Image();
    img.onload = () => {
      resolve({
        fileName: file.name,
        fileSizeKB: Math.max(1, Math.round(file.size / 1024)),
        mimeType: file.type || 'image',
        width: img.naturalWidth,
        height: img.naturalHeight,
      });
    };
    img.onerror = () => {
      resolve({
        fileName: file.name,
        fileSizeKB: Math.max(1, Math.round(file.size / 1024)),
        mimeType: file.type || 'image',
        width: 0,
        height: 0,
      });
    };
    img.src = previewUrl;
  });
}

function fileToDataUrl(file: File): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result));
    reader.onerror = () => reject(new Error('Failed to read image file.'));
    reader.readAsDataURL(file);
  });
}

export async function generateImageDescription(
  file: File,
  metadata: ImageMetadata
): Promise<ImageDescriptionResult> {
  if (isVisionApiConfigured() && VISION_API_URL) {
    const dataUrl = await fileToDataUrl(file);
    const headers: Record<string, string> = {
      'Content-Type': 'application/json',
    };
    if (VISION_API_KEY) {
      headers.Authorization = `Bearer ${VISION_API_KEY}`;
    }

    const response = await fetch(VISION_API_URL, {
      method: 'POST',
      headers,
      body: JSON.stringify({
        imageDataUrl: dataUrl,
        fileName: metadata.fileName,
        prompt:
          'Describe this image clearly and concisely for a blind or low-vision user.',
      }),
    });

    if (!response.ok) {
      throw new Error(`Vision API returned status ${response.status}`);
    }

    const payload = (await response.json()) as { description?: string; text?: string };
    const descriptionText = payload.description ?? payload.text;
    if (!descriptionText) {
      throw new Error('Vision API response did not include a description field.');
    }

    return {
      mode: 'api',
      description: descriptionText,
      details: 'Generated by connected Vision API.',
    };
  }

  // Honest Demo Mode: no fake AI guesses about image contents.
  const dimensionsText =
    metadata.width > 0 && metadata.height > 0
      ? `${metadata.width} by ${metadata.height} pixels`
      : 'unknown dimensions';
  const orientation =
    metadata.width > metadata.height
      ? 'landscape'
      : metadata.height > metadata.width
        ? 'portrait'
        : 'square';

  return {
    mode: 'demo',
    description: `Demo mode notice: No AI vision model is connected, so the visual contents of "${metadata.fileName}" were not analyzed. The uploaded image file is a ${orientation} ${metadata.mimeType} image measuring ${dimensionsText} (${metadata.fileSizeKB} KB). Connect a vision API to hear a real scene description.`,
    details:
      'Demo Mode active — browser file metadata is shown honestly without fabricated AI scene recognition.',
  };
}
